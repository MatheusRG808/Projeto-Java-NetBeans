    private void carregarFicha() {

        FichaTreinoDAO dao = new FichaTreinoDAO();

        FichaTreino ficha = dao.buscarPorCliente(cliente.getId());

        // Não existe ficha para esse cliente
        if (ficha == null) {
            return;
        }

        // Percorre os dias da semana
        for (Map.Entry<String, ComponentesDia> entrada
                : componentesDias.entrySet()) {

            String nomeDia = entrada.getKey();
            ComponentesDia c = entrada.getValue();

            DiaTreino dia = ficha.getTreino().get(nomeDia);

            if (dia == null) {
                continue;
            }

            // =====================================================
            // CARREGAR GRUPOS
            // =====================================================

            c.modeloGrupos.clear();

            for (String grupo : dia.getGrupos()) {

                if (!c.modeloGrupos.contains(grupo)) {
                    c.modeloGrupos.addElement(grupo);
                }
            }

            // =====================================================
            // CARREGAR EXERCÍCIOS
            // =====================================================

            atualizarExercicios(c);

            // =====================================================
            // SELECIONAR OS EXERCÍCIOS SALVOS
            // =====================================================

            for (String exercicioSelecionado
                    : dia.getExercicios()) {

                for (int i = 0;
                        i < c.modeloExercicios.size();
                        i++) {

                    String exercicio =
                            c.modeloExercicios.getElementAt(i);

                    if (exercicio.equals(exercicioSelecionado)) {

                        c.listaExercicios.addSelectionInterval(
                                i,
                                i
                        );

                        break;
                    }
                }
            }

            // =====================================================
            // CARREGAR DESCRIÇÃO
            // =====================================================

            c.descricao.setText(
                    dia.getDescricao() == null
                            ? ""
                            : dia.getDescricao()
            );
        }
    }
    
