    // =========================================================
    // ADICIONAR GRUPO
    // =========================================================

    private void adicionarGrupo(
            String dia) {

        ComponentesDia c =
                componentesDias.get(dia);

        String grupo =
                (String) c.comboGrupo.getSelectedItem();

        if (grupo == null ||
                grupo.equals("Selecione...")) {

            JOptionPane.showMessageDialog(
                    this,
                    "Selecione um grupo muscular."
            );

            return;
        }

        // -----------------------------------------------------
        // NÃO PERMITIR DUPLICADO
        // -----------------------------------------------------

        if (c.modeloGrupos.contains(grupo)) {

            JOptionPane.showMessageDialog(
                    this,
                    "Esse grupo muscular já foi adicionado."
            );

            return;
        }

        // -----------------------------------------------------
        // ADICIONA O GRUPO
        // -----------------------------------------------------

        c.modeloGrupos.addElement(
                grupo
        );

        c.comboGrupo.setSelectedIndex(
                0
        );

        // -----------------------------------------------------
        // ATUALIZA OS EXERCÍCIOS
        // -----------------------------------------------------

        atualizarExercicios(c);
    }

    // =========================================================
    // REMOVER GRUPO
    // =========================================================

    private void removerGrupo(
            String dia) {

        ComponentesDia c =
                componentesDias.get(dia);

        int indice =
                c.listaGrupos.getSelectedIndex();

        if (indice == -1) {

            JOptionPane.showMessageDialog(
                    this,
                    "Selecione um grupo para remover."
            );

            return;
        }

        c.modeloGrupos.remove(
                indice
        );

        atualizarExercicios(c);
    }

    // =========================================================
    // ATUALIZAR EXERCÍCIOS
    // =========================================================

    private void atualizarExercicios(
            ComponentesDia c) {

        /*
         * Guarda os exercícios que estavam
         * selecionados antes de atualizar.
         */
        List<String> selecionados =
                c.listaExercicios.getSelectedValuesList();

        c.modeloExercicios.clear();

        // -----------------------------------------------------
        // PERCORRE OS GRUPOS
        // -----------------------------------------------------

        for (int i = 0;
                i < c.modeloGrupos.size();
                i++) {

            String grupo =
                    c.modeloGrupos.getElementAt(i);

            List<String> exercicios =
                    exerciciosPorGrupo.get(
                            grupo
                    );

            if (exercicios == null) {
                continue;
            }

            // -------------------------------------------------
            // ADICIONA OS EXERCÍCIOS
            // -------------------------------------------------

            for (String exercicio :
                    exercicios) {

                if (!modeloContem(
                        c.modeloExercicios,
                        exercicio
                )) {

                    c.modeloExercicios.addElement(
                            exercicio
                    );
                }
            }
        }

        // -----------------------------------------------------
        // RESTAURA SELEÇÃO
        // -----------------------------------------------------

        for (int i = 0;
                i < c.modeloExercicios.size();
                i++) {

            String exercicio =
                    c.modeloExercicios.getElementAt(i);

            if (selecionados.contains(
                    exercicio
            )) {

                c.listaExercicios.addSelectionInterval(
                        i,
                        i
                );
            }
        }
    }

    // =========================================================
    // VERIFICAR SE MODELO POSSUI ITEM
    // =========================================================

    private boolean modeloContem(
            DefaultListModel<String> modelo,
            String valor) {

        for (int i = 0;
                i < modelo.size();
                i++) {

            if (modelo.getElementAt(i)
                    .equals(valor)) {

                return true;
            }
        }

        return false;
    }

    // =========================================================
    // OBTER FICHA
    // =========================================================

    public FichaTreino obterFicha() {

        FichaTreino ficha = new FichaTreino();

        for (Map.Entry<String, ComponentesDia> entrada : componentesDias.entrySet()) {
            String nomeDia = entrada.getKey();

            ComponentesDia c = entrada.getValue();

            DiaTreino dia = new DiaTreino();

            // -------------------------------------------------
            // GRUPOS
            // -------------------------------------------------

            List<String> grupos = new ArrayList<>();

            for (int i = 0; i < c.modeloGrupos.size(); i++) {
                grupos.add(c.modeloGrupos.getElementAt(i));
            }

            dia.setGrupos(grupos);

            // -------------------------------------------------
            // EXERCÍCIOS
            // -------------------------------------------------

            List<String> exercicios =
                    c.listaExercicios
                            .getSelectedValuesList();

            dia.setExercicios(new ArrayList<>(exercicios));

            // -------------------------------------------------
            // DESCRIÇÃO
            // -------------------------------------------------

            dia.setDescricao(c.descricao.getText());

            // -------------------------------------------------
            // COLOCA NO MAP
            // -------------------------------------------------

            ficha.getTreino().put(nomeDia, dia);
        }

        return ficha;
    }

    // =========================================================
    // SALVAR
    // =========================================================

    private void salvar() {

        FichaTreino ficha = obterFicha();

        FichaTreinoDAO dao = new FichaTreinoDAO();

        dao.salvar(cliente.getId(),ficha);

        JOptionPane.showMessageDialog(this, "Ficha de treino salva com sucesso!" );
    }

